USE ROLE ACCOUNTADMIN;

CREATE API INTEGRATION IF NOT EXISTS GITHUB_INT
  API_PROVIDER = git_https_api
  API_ALLOWED_PREFIXES = ('https://github.com/RoPillay')
  API_USER_AUTHENTICATION = (TYPE = SNOWFLAKE_GITHUB_APP)
  ENABLED = TRUE;

GRANT USAGE ON INTEGRATION GITHUB_INT TO ROLE DIVVY_ENGINEER;



USE ROLE ACCOUNTADMIN;

ALTER API INTEGRATION GITHUB_INT
  SET API_ALLOWED_PREFIXES = ('https://github.com/RoPillay', 'https://github.com/ropillay');

DESC INTEGRATION GITHUB_INT;